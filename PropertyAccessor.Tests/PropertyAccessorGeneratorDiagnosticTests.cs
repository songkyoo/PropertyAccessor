    [Test]
    public void Should_ReportDiagnosticAndKeepValidFields_When_ReadonlyFieldRequestsSetterMethod()
    {
        AssertGeneratedCode(
            sourceCode:
            """
            namespace Macaron.PropertyAccessor.Tests;

            public partial class Foo
            {
                [GetSet(setterName: "SetInvalid")]
                private readonly int _invalid;

                [GetSet(setterName: "")]
                private readonly int _valid;
            }
            """,
            expected:
            """
            // <auto-generated />
            #nullable enable

            namespace Macaron.PropertyAccessor.Tests
            {
                partial class Foo
                {
                    public int Valid
                    {
                        get => _valid;
                        init => _valid = value;
                    }
                }
            }

            """,
            out var diagnostics
        );

        Assert.That(diagnostics.Count(diagnostic => diagnostic.Id == "MPROP0009"), Is.EqualTo(1));
    }

    [Test]
    public void Should_ReportDiagnostic_When_SetterMethodsConflictWithDeclaredOrGeneratedMembers()
    {
        AssertGeneratedCode(
            sourceCode:
            """
            namespace Macaron.PropertyAccessor.Tests;

            public partial class Foo
            {
                public void SetCount(int value) { }

                [GetSet(setterName: "SetCount")]
                private int _count;

                [GetSet(setterName: "Value")]
                private int _answer;

                [Get]
                private int _value;

                [GetSet(setterName: "Update")]
                private int _first;

                [GetSet(setterName: "Update")]
                private int _second;
            }
            """,
            expected:
            """
            // <auto-generated />
            #nullable enable

            namespace Macaron.PropertyAccessor.Tests
            {
                partial class Foo
                {
                    public int Value
                    {
                        get => _value;
                    }
                }
            }

            """,
            out var diagnostics
        );

        Assert.That(diagnostics.Count(diagnostic => diagnostic.Id == "MPROP0010"), Is.EqualTo(4));
    }
