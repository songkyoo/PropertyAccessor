                [Get]
                private int _answer = 42;
            }
            """,
            expected:
            """
            // <auto-generated />
            #nullable enable

            namespace Macaron.PropertyAccessor.Tests
            {
                partial class Foo
                {
                    public int Answer
                    {
                        get => _answer;
                    }
                }
            }

            """,
            out var diagnostics
        );

        Assert.That(diagnostics.Count(diagnostic => diagnostic.Id == "MPROP0005"), Is.EqualTo(2));
    }

