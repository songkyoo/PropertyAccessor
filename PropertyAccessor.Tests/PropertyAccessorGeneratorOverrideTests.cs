    [Test]
    public void Should_OverrideClosestProperty_When_GenericBaseReabstractsProperty()
    {
        const string sourceCode =
            """
            namespace Macaron.PropertyAccessor.Tests;

            public class Root<T>
            {
                public virtual T Value { get; set; } = default!;
            }

            public abstract class Middle<T> : Root<T>
            {
                public abstract override T Value { get; set; }
            }

            public partial class Derived : Middle<int>
            {
                [GetSet]
                private int _value;
            }
            """;
        var compilation = CreateCompilation(sourceCode);

        var (output, result) = Generate(compilation);
        var derivedType = output.GetTypeByMetadataName("Macaron.PropertyAccessor.Tests.Derived")!;
        var property = derivedType.GetMembers("Value").OfType<IPropertySymbol>().Single();
        var overriddenType = property.OverriddenProperty?.ContainingType.ToDisplayString();
        var errors = output.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error);

        Assert.That(result.Diagnostics, Is.Empty);
        Assert.That(errors, Is.Empty);
        Assert.That(property.IsOverride, Is.True);
        Assert.That(overriddenType, Is.EqualTo("Macaron.PropertyAccessor.Tests.Middle<int>"));
    }

