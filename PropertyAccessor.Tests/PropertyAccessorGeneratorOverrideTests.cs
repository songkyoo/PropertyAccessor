    [Test]
    public void Should_ReadAndWriteDerivedField_When_AccessedThroughBaseReference()
    {
        const string sourceCode =
            """
            namespace Macaron.PropertyAccessor.Tests;

            public abstract class Base
            {
                public abstract int Value { get; set; }
            }

            public partial class Derived : Base
            {
                [GetSet]
                private int _value = 17;
            }

            public static class Scenario
            {
                public static string Run()
                {
                    Base instance = new Derived();
                    var initial = instance.Value;

                    instance.Value = 42;

                    return $"{initial}:{instance.Value}";
                }
            }
            """;
        var compilation = CreateCompilation(sourceCode).WithAssemblyName($"OverrideRuntime_{Guid.NewGuid():N}");
        var loadContext = new AssemblyLoadContext(compilation.AssemblyName, isCollectible: true);
        using var stream = new MemoryStream();

        var (output, result) = Generate(compilation);
        var emitResult = output.Emit(stream);

        Assert.That(result.Diagnostics, Is.Empty);
        Assert.That(emitResult.Success, Is.True, string.Join(Environment.NewLine, emitResult.Diagnostics));

        try
        {
            stream.Position = 0;

            var assembly = loadContext.LoadFromStream(stream);
            var scenario = assembly.GetType("Macaron.PropertyAccessor.Tests.Scenario")!;
            var run = scenario.GetMethod("Run", BindingFlags.Public | BindingFlags.Static)!;

            var value = run.Invoke(obj: null, parameters: null);

            Assert.That(value, Is.EqualTo("17:42"));
        }
        finally
        {
            loadContext.Unload();
        }
    }
