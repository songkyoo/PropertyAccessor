    #region Static
    private static (Compilation Output, GeneratorRunResult Result) Generate(CSharpCompilation compilation)
    {
        var driver = CreateGeneratorDriver().RunGeneratorsAndUpdateCompilation(
            compilation,
            out var output,
            out _
        );

        return (output, driver.GetRunResult().Results.Single());
    }

    private static MetadataReference CompileBaseAssembly(string sourceCode)
    {
        var compilation = CreateCompilation(sourceCode).WithAssemblyName("OverrideBase");
        using var stream = new MemoryStream();

        var emitResult = compilation.Emit(stream);

        Assert.That(emitResult.Success, Is.True, string.Join(Environment.NewLine, emitResult.Diagnostics));

        return MetadataReference.CreateFromImage(stream.ToArray());
    }
