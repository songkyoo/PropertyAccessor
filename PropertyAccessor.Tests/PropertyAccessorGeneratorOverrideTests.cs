    public void Should_ReportErrorAndKeepOtherFields_When_OverrideContractDoesNotMatch(
        string baseProperty,
        string attribute,
        string field,
        string expectedReason
    )
    {
        var sourceCode =
            $$"""
            namespace Macaron.PropertyAccessor.Tests;

            public abstract class Base
            {
                {{baseProperty}}
            }

            public partial class Derived : Base
            {
                {{attribute}}
                {{field}}

                [Get]
                private int _valid;
            }
            """;

        AssertGeneratedCode(
            sourceCode,
            expected:
            """
            // <auto-generated />
            #nullable enable

            namespace Macaron.PropertyAccessor.Tests
            {
                partial class Derived
                {
                    public int Valid
                    {
                        get => _valid;
                    }
                }
            }

            """,
            out var diagnostics
        );
        var overrideDiagnostic = diagnostics.Single(diagnostic => diagnostic.Id == "MPROP0011");
        var message = overrideDiagnostic.GetMessage();
        var diagnosticText = sourceCode.Substring(
            overrideDiagnostic.Location.SourceSpan.Start,
            overrideDiagnostic.Location.SourceSpan.Length
        );

        Assert.That(overrideDiagnostic.Severity, Is.EqualTo(DiagnosticSeverity.Error));
        Assert.That(message, Does.Contain("Base.Value").And.Contain(expectedReason));
        Assert.That(diagnosticText, Is.EqualTo("_value"));
    }

